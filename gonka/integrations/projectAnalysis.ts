function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === "string");
}

function isValidPercentage(value: unknown): value is number {
  return (
    typeof value === "number" &&
    Number.isFinite(value) &&
    Number.isInteger(value) &&
    value >= 1 &&
    value <= 100
  );
}

type MilestoneStage =
  | "PLANNING_DESIGN"
  | "CORE_DEVELOPMENT"
  | "INTEGRATION_FEATURES"
  | "TESTING_DEPLOYMENT";

function normalise(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[–—]/g, "-")
    .replace(/\s+/g, " ");
}

function classifyMilestoneStage(
  title: string,
  description: string,
): MilestoneStage {
  const text = `${title} ${description}`.toLowerCase();

  if (
    text.includes("test") ||
    text.includes("qa") ||
    text.includes("deploy") ||
    text.includes("launch") ||
    text.includes("handover") ||
    text.includes("documentation")
  ) {
    return "TESTING_DEPLOYMENT";
  }

  if (
    text.includes("payment") ||
    text.includes("gateway") ||
    text.includes("auth") ||
    text.includes("integration") ||
    text.includes("admin") ||
    text.includes("notification") ||
    text.includes("smart contract") ||
    text.includes("escrow")
  ) {
    return "INTEGRATION_FEATURES";
  }

  if (
    text.includes("design") ||
    text.includes("architecture") ||
    text.includes("wireframe") ||
    text.includes("spec") ||
    text.includes("planning") ||
    text.includes("setup") ||
    text.includes("prototype")
  ) {
    return "PLANNING_DESIGN";
  }

  return "CORE_DEVELOPMENT";
}

interface RawMilestone {
  title: string;
  description: string;
  percentageAllocation: number;
}

/**
 * Deterministic safety validation BEFORE the multi-model verification.
 *
 * This does not replace multi-model verification.
 * It only prevents structurally invalid primary output. Semantic duplicate
 * detection is intentionally handled by the independent verifier models.
 */
function validateMilestones(value: unknown): RawMilestone[] {
  if (!Array.isArray(value)) {
    throw new Error("Invalid milestones format");
  }

  if (value.length < 2 || value.length > 6) {
    throw new Error("Milestones must contain between 2 and 6 items");
  }

  const milestones = value.map((item, index) => {
    if (!item || typeof item !== "object") {
      throw new Error(`Invalid milestone at index ${index}`);
    }

    const data = item as Record<string, unknown>;

    if (typeof data.title !== "string" || !data.title.trim()) {
      throw new Error(`Invalid milestone title at index ${index}`);
    }

    if (typeof data.description !== "string" || !data.description.trim()) {
      throw new Error(`Invalid milestone description at index ${index}`);
    }

    if (!isValidPercentage(data.percentageAllocation)) {
      throw new Error(`Invalid milestone percentage at index ${index}`);
    }

    return {
      title: data.title.trim(),
      description: data.description.trim(),
      percentageAllocation: data.percentageAllocation,
    };
  });

  const total = milestones.reduce(
    (sum, milestone) => sum + milestone.percentageAllocation,
    0,
  );

  if (total !== 100) {
    throw new Error(
      `Milestone percentages must total exactly 100. Received ${total}`,
    );
  }

  /*
   * IMPORTANT:
   * Do NOT reject milestones merely because they belong to the same broad
   * development stage.
   *
   * For example:
   *   - Authentication & User Management
   *   - Payment Gateway Integration
   *
   * can both be integration-related while still being two legitimate,
   * different milestones.
   *
   * Genuine duplicate milestone detection is delegated to the independent
   * MiniMax + DeepSeek verification stage, where the models can understand
   * the semantic purpose of each milestone.
   *
   * We only perform basic structural validation here.
   */

  return milestones;
}

/**
 * Converts AI-generated percentages into exact currency amounts.
 * Uses the Largest Remainder Method to prevent rounding loss.
 */
export function calculateMilestoneAmounts(
  milestones: RawMilestone[],
  budget: ProjectBudget,
): ProjectMilestone[] {
  const totalCents = Math.round(budget.amount * 100);

  const exactAmounts = milestones.map(
    (milestone) =>
      (totalCents * milestone.percentageAllocation) / 100,
  );

  const amounts = exactAmounts.map((amount) => Math.floor(amount));

  let remaining =
    totalCents - amounts.reduce((sum, amount) => sum + amount, 0);

  const remainderOrder = exactAmounts
    .map((exact, index) => ({
      index,
      fraction: exact - amounts[index],
    }))
    .sort((a, b) => b.fraction - a.fraction);

  for (const item of remainderOrder) {
    if (remaining <= 0) break;
    amounts[item.index] += 1;
    remaining -= 1;
  }

  return milestones.map((milestone, index) => ({
    title: milestone.title,
    description: milestone.description,
    percentageAllocation: milestone.percentageAllocation,
    amount: amounts[index] / 100,
  }));
}

/* ============================================================
   ANALYSIS VALIDATION
   ============================================================ */

function validateAnalysis(
  value: unknown,
  requirements: ProjectAssistantRequirements,
): ProjectAnalysis {
  if (!value || typeof value !== "object") {
    throw new Error("Project analysis is not an object");
  }

  const data = value as Record<string, unknown>;

  if (typeof data.projectTitle !== "string") {
    throw new Error("Invalid projectTitle");
  }

  if (typeof data.projectDescription !== "string") {
    throw new Error("Invalid projectDescription");
  }

  if (typeof data.projectType !== "string") {
    throw new Error("Invalid projectType");
  }

  if (data.platform !== null && typeof data.platform !== "string") {
    throw new Error("Invalid platform");
  }

  if (!isStringArray(data.targetUsers)) {
    throw new Error("Invalid targetUsers");
  }

  if (!isStringArray(data.coreFeatures)) {
    throw new Error("Invalid coreFeatures");
  }

  const validComplexities: ProjectComplexity[] = [
    "Simple",
    "Moderate",
    "Complex",
    "Highly Complex",
  ];

  if (!validComplexities.includes(data.complexity as ProjectComplexity)) {
    throw new Error("Invalid complexity");
  }

  if (!isStringArray(data.requiredSkills)) {
    throw new Error("Invalid requiredSkills");
  }

  const validExperienceLevels: ExperienceLevel[] = [
    "Beginner",
    "Intermediate",
    "Expert",
  ];

  if (
    !validExperienceLevels.includes(
      data.experienceLevel as ExperienceLevel,
    )
  ) {
    throw new Error("Invalid experienceLevel");
  }

  if (!isStringArray(data.keyDeliverables)) {
    throw new Error("Invalid keyDeliverables");
  }

  if (!isStringArray(data.technicalConsiderations)) {
    throw new Error("Invalid technicalConsiderations");
  }

  if (!data.budget || typeof data.budget !== "object") {
    throw new Error("Invalid budget");
  }

  const budget = data.budget as Record<string, unknown>;

  if (
    typeof budget.amount !== "number" ||
    !Number.isFinite(budget.amount) ||
    budget.amount <= 0
  ) {
    throw new Error("Invalid budget amount");
  }

  if (typeof budget.currency !== "string" || !budget.currency.trim()) {
    throw new Error("Invalid budget currency");
  }

  const validBudgetAssessments: BudgetAssessment[] = [
    "REASONABLE",
    "POSSIBLY_LOW",
    "POSSIBLY_HIGH",
    "UNKNOWN",
  ];

  if (
    !validBudgetAssessments.includes(
      data.budgetAssessment as BudgetAssessment,
    )
  ) {
    throw new Error("Invalid budgetAssessment");
  }

  if (
    typeof data.estimatedTimelineDays !== "number" ||
    !Number.isInteger(data.estimatedTimelineDays) ||
    data.estimatedTimelineDays <= 0
  ) {
    throw new Error("Invalid estimatedTimelineDays");
  }

  const validTimelineAssessments: TimelineAssessment[] = [
    "REASONABLE",
    "POSSIBLY_TOO_SHORT",
    "POSSIBLY_TOO_LONG",
    "UNKNOWN",
  ];

  if (
    !validTimelineAssessments.includes(
      data.timelineAssessment as TimelineAssessment,
    )
  ) {
    throw new Error("Invalid timelineAssessment");
  }

  const rawMilestones = validateMilestones(data.milestones);

  /**
   * Budget and timeline are authoritative from Project Assistant.
   * The primary model is not allowed to alter them.
   */
  if (
    budget.amount !== requirements.budget.amount ||
    normalise(budget.currency as string) !==
      normalise(requirements.budget.currency)
  ) {
    throw new Error(
      "Primary analysis changed the approved project budget",
    );
  }

  if (data.estimatedTimelineDays !== requirements.timeline.days) {
    throw new Error(
      "Primary analysis changed the approved project timeline",
    );
  }

  const projectBudget: ProjectBudget = {
    amount: budget.amount as number,
    currency: budget.currency as string,
  };

  return {
    projectTitle: data.projectTitle,
    projectDescription: data.projectDescription,
    projectType: data.projectType,
    platform: data.platform as string | null,
    targetUsers: data.targetUsers,
    coreFeatures: data.coreFeatures,
    complexity: data.complexity as ProjectComplexity,
    requiredSkills: data.requiredSkills,
    experienceLevel: data.experienceLevel as ExperienceLevel,
    keyDeliverables: data.keyDeliverables,
    technicalConsiderations: data.technicalConsiderations,
    budget: projectBudget,
    budgetAssessment: data.budgetAssessment as BudgetAssessment,
    estimatedTimelineDays: data.estimatedTimelineDays,
    timelineAssessment: data.timelineAssessment as TimelineAssessment,
    milestones: calculateMilestoneAmounts(rawMilestones, projectBudget),
  };
}

