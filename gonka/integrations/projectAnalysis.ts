export async function analyzeProjectWithGonka(
  requirements: ProjectAssistantRequirements,
  model?: string,
): Promise<ProjectAnalysisModelResult> {
  const selectedModel = model ?? process.env.GONKA_MODEL ?? "deepseek-ai/DeepSeek-V4-Flash-0731";

  const prompt = buildProjectAnalysisPrompt(requirements);

  console.log(`Sending Project Analysis request to Gonka model: ${selectedModel}`);

  const startTime = Date.now();

  const response = await gonka.chat.completions.create({
    model: selectedModel,
    messages: [
      {
        role: "system",
        content: "You are TrustHire's Project Analysis AI. Return only valid JSON.",
      },
      {
        role: "user",
        content: prompt,
      },
    ],
    temperature: 0,
  });

  const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
  console.log(`Received Project Analysis response from ${selectedModel} in ${elapsed}s`);

  const content = response.choices[0]?.message?.content;

  if (!content) {
    throw new Error("Gonka returned an empty Project Analysis response");
  }

  let parsed: Record<string, unknown>;

  try {
    parsed = parseGonkaJson(content) as Record<string, unknown>;
  } catch {
    throw new Error(`Gonka returned invalid Project Analysis JSON: ${content}`);
  }

  const analysis = validateAnalysis(parsed);

  const confidence = parsed.confidence;
  if (confidence !== "LOW" && confidence !== "MEDIUM" && confidence !== "HIGH") {
    throw new Error("Invalid Project Analysis confidence");
  }

  const reasoning = parsed.reasoning;
  if (typeof reasoning !== "string") {
    throw new Error("Invalid Project Analysis reasoning");
  }

  return {
    model: selectedModel,
    analysis,
    confidence,
    reasoning,
    requestId: response.id ?? "unknown",
  };
}

