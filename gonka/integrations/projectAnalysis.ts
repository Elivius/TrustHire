/* ============================================================
   SINGLE MODEL VERIFICATION
   ============================================================ */

export async function verifyProjectAnalysisWithGonka(
  requirements: ProjectAssistantRequirements,
  analysis: ProjectAnalysis,
  model: string,
): Promise<ProjectAnalysisVerificationResult> {
  const prompt = buildVerificationPrompt(requirements, analysis);

  console.log(
    `Sending Project Analysis VERIFICATION request to Gonka model: ${model}`,
  );

  const startTime = Date.now();

  const result = await gonka.chat.completions
    .create({
      model,
      messages: [
        {
          role: "system",
          content:
            "You are TrustHire's independent Project Analysis Verifier. Return only valid JSON.",
        },
        {
          role: "user",
          content: prompt,
        },
      ],
      temperature: 0,
    })
    .withResponse();

  const response = result.data;
  const requestId = result.request_id;

  const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
  console.log(
    `Received Project Analysis verification from ${model} in ${elapsed}s`,
  );

  const content = response.choices[0]?.message?.content;

  if (!content) {
    throw new Error(
      `Gonka returned an empty verification response from ${model}`,
    );
  }

  let parsed: Record<string, unknown>;

  try {
    parsed = parseGonkaJson(content) as Record<string, unknown>;
  } catch {
    throw new Error(
      `Gonka returned invalid verification JSON from ${model}: ${content}`,
    );
  }

  const status = parsed.status;
  if (status !== "PASS" && status !== "FAIL") {
    throw new Error(`Invalid verification status from ${model}`);
  }

  const confidence = parsed.confidence;
  if (
    confidence !== "LOW" &&
    confidence !== "MEDIUM" &&
    confidence !== "HIGH"
  ) {
    throw new Error(`Invalid verification confidence from ${model}`);
  }

  const issues = parsed.issues;
  if (!isStringArray(issues)) {
    throw new Error(`Invalid verification issues from ${model}`);
  }

  if (!parsed.checks || typeof parsed.checks !== "object") {
    throw new Error(`Invalid verification checks from ${model}`);
  }

  const checks = parsed.checks as Record<string, unknown>;

  const checkNames = [
    "requirementsAlignment",
    "structureValidity",
    "milestoneValidity",
    "milestoneUniqueness",
    "allocationValidity",
    "budgetTimelinePreserved",
    "completeness",
  ] as const;

  for (const checkName of checkNames) {
    if (typeof checks[checkName] !== "boolean") {
      throw new Error(
        `Invalid verification check '${checkName}' from ${model}`,
      );
    }
  }

  const reasoning = parsed.reasoning;
  if (typeof reasoning !== "string") {
    throw new Error(`Invalid verification reasoning from ${model}`);
  }

  return {
    model,
    status,
    confidence,
    issues,
    checks: {
      requirementsAlignment: checks.requirementsAlignment as boolean,
      structureValidity: checks.structureValidity as boolean,
      milestoneValidity: checks.milestoneValidity as boolean,
      milestoneUniqueness: checks.milestoneUniqueness as boolean,
      allocationValidity: checks.allocationValidity as boolean,
      budgetTimelinePreserved: checks.budgetTimelinePreserved as boolean,
      completeness: checks.completeness as boolean,
    },
    reasoning,
    requestId: requestId ?? "unknown",
  };
}

/* ============================================================
   VERIFICATION CONSENSUS
   ============================================================ */

/**
 * All verifier models judge the SAME primary analysis.
 *
 * A PASS requires a strict majority of successful verifiers.
 * With two verifiers, both must PASS.
 */
function calculateVerificationConsensus(
  verifierResults: ProjectAnalysisVerificationResult[],
): ProjectAnalysisVerification {
  if (verifierResults.length === 0) {
    throw new Error("No successful Project Analysis verifiers");
  }

  const passedCount = verifierResults.filter(
    (result) => result.status === "PASS",
  ).length;

  const failedCount = verifierResults.length - passedCount;

  /**
   * Strict majority:
   * 1 verifier  -> 1/1
   * 2 verifiers -> 2/2
   * 3 verifiers -> 2/3
   * 4 verifiers -> 3/4
   */
  const requiredPasses = Math.floor(verifierResults.length / 2) + 1;

  const passed = passedCount >= requiredPasses;

  let resolutionMethod: VerificationResolutionMethod;

  if (passedCount === verifierResults.length) {
    resolutionMethod = "CONSENSUS";
  } else if (passed) {
    resolutionMethod = "MAJORITY";
  } else {
    resolutionMethod = "REJECTED";
  }

  const confidence: "LOW" | "MEDIUM" | "HIGH" =
    passedCount === verifierResults.length
      ? "HIGH"
      : passed
        ? "MEDIUM"
        : "LOW";

  const allIssues = verifierResults.flatMap((result) =>
    result.issues.map((issue) => `[${result.model}] ${issue}`),
  );

  const reasoning = passed
    ? `${passedCount}/${verifierResults.length} independent verifier(s) passed the same primary analysis.`
    : `${passedCount}/${verifierResults.length} independent verifier(s) passed. The primary analysis was rejected. ${
        allIssues.length > 0
          ? `Issues: ${allIssues.join(" | ")}`
          : "One or more verifiers found the analysis unsuitable."
      }`;

  return {
    status: passed ? "PASS" : "FAIL",
    passedCount,
    failedCount,
    totalModels: verifierResults.length,
    confidence,
    resolutionMethod,
    verifierResults,
    reasoning,
  };
}

/* ============================================================
   MODEL SELECTION
   ============================================================ */

function getPrimaryModel(): string {
  // TrustHire's primary model is MiniMax.
  return (
    process.env.GONKA_MODEL?.trim() ||
    "MiniMaxAI/MiniMax-M2.7"
  );
}

function getVerifierModels(_primaryModel: string): string[] {
  /**
   * TrustHire verification uses TWO independent verification calls:
   *
   * 1. MiniMax
   * 2. DeepSeek
   *
   * MiniMax is intentionally allowed to verify the analysis even though
   * MiniMax is also the primary analysis model. The verifier uses a
   * different prompt and receives the already-generated primary analysis;
   * it does NOT generate a replacement analysis.
   *
   * You can override these defaults with:
   *
   * GONKA_VERIFIER_MODELS=MiniMaxAI/MiniMax-M2.7,deepseek-ai/DeepSeek-V4-Flash-0731
   */
  const configuredVerifiers = process.env.GONKA_VERIFIER_MODELS
    ?.split(",")
    .map((model) => model.trim())
    .filter(Boolean);

  const candidates =
    configuredVerifiers && configuredVerifiers.length > 0
      ? configuredVerifiers
      : [
          "MiniMaxAI/MiniMax-M2.7",
          "deepseek-ai/DeepSeek-V4-Flash-0731",
        ];

  const unique = [...new Set(candidates.map((model) => model.trim()))];

  if (unique.length === 0) {
    throw new Error(
      "No Project Analysis verifier models configured.",
    );
  }

  return unique;
}

/* ============================================================
   MAIN PROJECT ANALYSIS ENTRY POINT
   ============================================================ */

/**
 * TrustHire Project Analysis pipeline:
 *
 * STEP 1:
 * One PRIMARY model generates the complete project structure.
 *
 * STEP 2:
 * MiniMax and DeepSeek independently receive that exact same structure
 * and judge it. They do NOT generate alternative structures.
 *
 * STEP 3:
 * MiniMax and DeepSeek vote PASS/FAIL.
 *
 * With the default two-verifier setup, BOTH must PASS for approval.
 *
 * STEP 4:
 * The primary analysis is returned unchanged. It should only be published
 * / used for escrow when verification.status === "PASS".
 */
export async function analyzeProject(
  requirements: ProjectAssistantRequirements,
): Promise<ProjectAnalysisResult> {
  if (!requirements || typeof requirements !== "object") {
    throw new Error("Project Assistant requirements are required");
  }

  if (!requirements.projectTitle?.trim()) {
    throw new Error("Project title is required");
  }

  if (!requirements.description?.trim()) {
    throw new Error("Project description is required");
  }

  if (!Array.isArray(requirements.coreFeatures)) {
    throw new Error("Project core features are required");
  }

  if (
    !requirements.budget ||
    typeof requirements.budget.amount !== "number" ||
    !Number.isFinite(requirements.budget.amount) ||
    requirements.budget.amount <= 0
  ) {
    throw new Error("Approved project budget is required");
  }

  if (
    !requirements.timeline ||
    typeof requirements.timeline.days !== "number" ||
    !Number.isInteger(requirements.timeline.days) ||
    requirements.timeline.days <= 0
  ) {
    throw new Error("Approved project timeline is required");
  }

  /* ----------------------------------------------------------
     STEP 1: ONE PRIMARY MODEL CREATES THE STRUCTURE
     ---------------------------------------------------------- */

  const primaryModel = getPrimaryModel();

  console.log(
    `Running ONE PRIMARY Project Analysis model: ${primaryModel}`,
  );

  const primaryResult = await analyzeProjectWithGonka(
    requirements,
    primaryModel,
  );

  console.log(
    `Primary analysis created. Starting independent multi-model verification...`,
  );

  /* ----------------------------------------------------------
     STEP 2: MULTIPLE MODELS VERIFY THE SAME STRUCTURE
     ---------------------------------------------------------- */

  const verifierModels = getVerifierModels(primaryModel);

  console.log(
    `Running ${verifierModels.length} independent Project Analysis verifier(s) in parallel...`,
  );

  const execution = await runAcrossModels(verifierModels, (model) =>
    verifyProjectAnalysisWithGonka(
      requirements,
      primaryResult.analysis,
      model,
    ),
  );

  const successfulVerifications = execution.results.filter(
    (
      result,
    ): result is typeof result & {
      success: true;
      result: ProjectAnalysisVerificationResult;
    } => result.success && result.result !== undefined,
  );

  const failedVerificationCalls = execution.results.filter(
    (result) => !result.success,
  ).length;

  if (successfulVerifications.length === 0) {
    throw new Error(
      "All Project Analysis verifier models failed to return a valid verification.",
    );
  }

  const verifierResults = successfulVerifications.map(
    (result) => result.result,
  );

  const verification = calculateVerificationConsensus(verifierResults);

  console.log(
    `Project Analysis verification result: ${verification.status} (${verification.passedCount}/${verification.totalModels} passed)`,
  );

  if (verification.status === "FAIL") {
    console.warn(
      `Primary Project Analysis REJECTED by multi-model verification.`,
    );
    console.warn(
      `Verifier issues: ${verification.verifierResults
        .flatMap((result) =>
          result.issues.map((issue) => `[${result.model}] ${issue}`),
        )
        .join(" | ")}`,
    );
  } else {
    console.log(
      `Primary Project Analysis APPROVED by multi-model verification.`,
    );
  }

  /* ----------------------------------------------------------
     STEP 3: RETURN PRIMARY ANALYSIS + VERIFICATION
     ---------------------------------------------------------- */

return {
  analysis: primaryResult.analysis,
  verification,

  primaryRequestId: primaryResult.requestId,

  verifierRequestIds: verifierResults.map((result) => ({
    model: result.model,
    requestId: result.requestId,
  })),

  successfulModels: 1,
  failedModels: failedVerificationCalls,
};
}
